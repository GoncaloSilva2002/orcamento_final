-- Aba "Carpintaria" em "Mudar preço fornecedores".
CREATE TABLE IF NOT EXISTS public.carpintaria (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referencia text NOT NULL,
  id_fornecedor bigint REFERENCES public.fornecedor(id),
  preco_fornecedor numeric NOT NULL DEFAULT 0 CHECK (preco_fornecedor >= 0),
  custo numeric NOT NULL DEFAULT 0 CHECK (custo >= 0),
  preco_cliente numeric NOT NULL DEFAULT 0 CHECK (preco_cliente >= 0),
  preco_revendedor numeric NOT NULL DEFAULT 0 CHECK (preco_revendedor >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

