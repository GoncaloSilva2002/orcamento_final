-- Custos personalizados apresentados na aba "Custos".
CREATE TABLE IF NOT EXISTS public.custos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  tipo text NOT NULL DEFAULT 'outro',
  custo numeric NOT NULL DEFAULT 0 CHECK (custo >= 0),
  preco_cliente numeric NOT NULL DEFAULT 0 CHECK (preco_cliente >= 0),
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_custos_tipo ON public.custos(tipo);

