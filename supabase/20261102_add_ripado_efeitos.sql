-- Aba "Ripado/Efeitos" em "Mudar preço fornecedores".
-- O Ripado custa 85 EUR ao cliente por unidade; a partir de 10 unidades o
-- orçamento aplica 65% desse valor (regra no servidor, não na tabela).
CREATE TABLE IF NOT EXISTS public.ripado_efeitos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referencia text NOT NULL,
  id_fornecedor bigint REFERENCES public.fornecedor(id),
  preco_fornecedor numeric NOT NULL DEFAULT 0 CHECK (preco_fornecedor >= 0),
  custo numeric NOT NULL DEFAULT 0 CHECK (custo >= 0),
  preco_cliente numeric NOT NULL DEFAULT 0 CHECK (preco_cliente >= 0),
  preco_revendedor numeric NOT NULL DEFAULT 0 CHECK (preco_revendedor >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO public.ripado_efeitos (referencia, preco_cliente, preco_revendedor)
SELECT 'Ripado', 85, 85
WHERE NOT EXISTS (SELECT 1 FROM public.ripado_efeitos WHERE referencia = 'Ripado');

-- Preço cliente calculado no orçamento: 15% do preço unitário do módulo escolhido.
INSERT INTO public.ripado_efeitos (referencia, preco_cliente, preco_revendedor)
SELECT 'Efeito almofada recuada', 0, 0
WHERE NOT EXISTS (SELECT 1 FROM public.ripado_efeitos WHERE referencia = 'Efeito almofada recuada');

